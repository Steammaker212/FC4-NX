#!/usr/bin/env python3
"""fc4-nx: writes out/fc4_d3d/hook_map.txt, Far Cry 4's address for every Direct3D hook in Renut's tree
(app/src/renut_engine/gpu/d3d/hooks/*.cpp, katamari-nx's addresses) and for sa2-nx's extra hooks.

Sources: the state tables (render 0x84174F78, sampler 0x84175438: {getter, setter, default} x 101 / 20, the same
counts as N&B's and Katamari's, so index i is state i), and tools/fc4_d3d/fc4_hook_map_hand.txt (everything else,
with its evidence). A hook found in neither is listed as unresolved with the reason.

  python -P tools/fc4_d3d/make_map.py
"""
import os, re, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fc4lib as L
from list_hooks import scan

RENDER, SAMPLER = (0x84174F78, 101), (0x84175438, 20)
STATE = re.compile(r'(render|sampler) state (\d+) (getter|setter)')
SA2_EXTRA = {  # sa2-nx hooks with no line in katamari-nx's tree (or unhooked there)
    'D3D_CDevice_NewSegment': 'SA2 ring segment allocator (sa2-nx Sa2NewSegment_hook)',
    'D3D_CDevice_AllocateInlineData': 'sa2-nx hooks it (HOOK_SHARED); unhooked in katamari-nx',
    'XGRegisterPixelShader': 'sa2-nx hooks it (raw); unhooked in katamari-nx',
    'D3D_ResolveCore': 'sa2-nx native resolve chain reference',
}
NOT_NEEDED = ('resource.cpp',)


def table(g, base, n):
    return [struct.unpack_from('>III', g.data, base - L.BASE + 12 * i) for i in range(n)]


def main():
    g = L.load()
    rs, ss = table(g, *RENDER), table(g, *SAMPLER)
    hand = {}
    for ln in open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'fc4_hook_map_hand.txt'), encoding='utf-8'):
        if not ln.strip() or ln.startswith('#'):
            continue
        name, fc4, sa2, conf, ev = ln.rstrip('\n').split(None, 4)
        hand[name] = (fc4, sa2, conf, ev)
    rows = []
    seen = set()
    for h in scan(L.ROOT):
        name, kind = h['name'], ('tree-hooked' if not h['un'] else 'tree-unhooked')
        m = STATE.search(h['rest'])
        key = name
        if m:
            which, i, gs = m.group(1), int(m.group(2)), m.group(3)
            rec = (rs if which == 'render' else ss)[i]
            fc4 = rec[0] if gs == 'getter' else rec[1]
            tbl = RENDER[0] if which == 'render' else SAMPLER[0]
            rows.append((h['file'], kind, name, f'{fc4:08X}', '-', 'high',
                         f'{which} state table {tbl:08X} record {i} ({gs}; default {rec[2]:08X}); tree: Katamari {h["sub"][4:]}'))
            continue
        alias = {'D3DDevice_SetTexture_Inline': None, 'D3D_SetViewport': 'D3D_SetViewport'}
        if name in hand:
            fc4, sa2, conf, ev = hand[name]
            seen.add(name)
            rows.append((h['file'], kind, name, fc4, sa2, conf if fc4 != '-' else 'unresolved', ev))
        elif not name:
            raw = {'sub_824EFBC8': 'D3DDevice_BeginTiling', 'sub_824F0150': 'D3DDevice_EndTiling'}.get(h['sub'])
            if raw:
                fc4, sa2, conf, ev = hand[raw]
                rows.append((h['file'], kind, raw + '(raw)', fc4, sa2, conf, ev + '; the raw BeginTilingImpl / EndTilingImpl hook'))
        else:
            if h['file'] in NOT_NEEDED:
                why = ('unresolved: not identified in this pass. A katamari-nx native resource hook; sa2-nx (whose '
                       'layout FC4 has) keeps the resource functions as the game\'s code and hooks only D3DResource_Destroy')
            elif h['file'] == 'state.cpp':
                why = ('unresolved: not identified in this pass. A katamari-nx native state hook; under sa2-nx\'s design '
                       '(state.cpp not built) the game\'s own function runs')
            else:
                why = 'unresolved: not identified in this pass'
            rows.append((h['file'], kind, name, '-', '-', 'unresolved', why + f'; tree: Katamari {h["sub"][4:]}'))
    for name, (fc4, sa2, conf, ev) in hand.items():
        if name not in seen:
            tag = SA2_EXTRA.get(name, 'not a hook line in the tree (helper / sa2-nx reference)')
            rows.append(('-', 'extra', name, fc4, sa2, conf if fc4 != '-' else 'unresolved', f'{ev} [{tag}]'))
    out = os.path.join(L.OUT, 'hook_map.txt')
    with open(out, 'w', encoding='utf-8') as f:
        f.write('# fc4-nx (2026-11-09): Far Cry 4 (XDK 2.0.21256) Direct3D hook map. Generated by tools/fc4_d3d/make_map.py\n'
                '# from the state tables and tools/fc4_d3d/fc4_hook_map_hand.txt; docs/fc4-d3d-map.md explains the method.\n'
                '# Columns: file (hooks/*.cpp of the tree, - = not a tree hook), tree status, function, FC4 address, SA2 address,\n'
                '# confidence, evidence. Tree status: tree-hooked / tree-unhooked (katamari-nx BANJO_RENUT_UNHOOKED) / extra.\n')
        for r in rows:
            f.write(f'{r[0]:<13} {r[1]:<14} {r[2]:<42} {r[3]:<9} {r[4]:<9} {r[5]:<10} {r[6]}\n')
    from collections import Counter
    c = Counter((r[1], r[5]) for r in rows)
    print(out, len(rows), 'rows')
    for k in sorted(c):
        print(' ', k, c[k])


if __name__ == '__main__':
    main()
